# =============================================================================
# 文件：gesture/finger_state.py
# 职责：【识别层第一步 - 手指状态判断】
#       接收一只手的 21 个关键点坐标，判断每根手指是"伸出"还是"弯曲"，
#       输出一个 5 位的状态列表，供后续手势分类使用
#
# 输入：21 个关键点列表 + 左右手标签
# 输出：[拇指, 食指, 中指, 无名指, 小指]，每位取值 1（伸出）或 0（弯曲）
#
# 判断原理（屏幕坐标系）：
#   屏幕坐标的 y 轴方向是向下的！
#   即 y=0 在屏幕最上方，y 越大越靠近屏幕底部
#
#   对于四根手指（食指、中指、无名指、小指）：
#     若指尖的 y 坐标 < 第二关节(PIP)的 y 坐标
#     → 指尖在关节上方 → 手指是伸直的 → 状态 = 1
#   对于拇指（方向是横向的，需要比较 x 坐标）
#   因画面已镜像，需要根据左右手分别处理
# =============================================================================


def get_finger_state(hand, handedness="Unknown"):
    """
    @function:
        根据 21 个关键点判断五根手指的伸屈状态

    @params:
        hand (list): 一只手的21 个关键点的二维列表，格式如下：
        hand = [
            [0, x, y], 
            [1, x, y], 
            [2, x, y], 
            ..., 
            [20, x, y]
        ]
        其中 hand[n] 表示第 n 号关键点，hand[n][1] 是 x 坐标，hand[n][2] 是 y 坐标

        handedness (str): MediaPipe 返回的左右手标签，"Left" 或 "Right" 或 "Unknown"
            注意：由于画面做了镜像翻转，MediaPipe 说的 "Left" 其实是用户的右手！
            即 MediaPipe "Left" = 屏幕左侧的手 = 镜像后的用户右手

    @returns:
        fingers (list): 长度为 5 的列表，顺序是 [拇指, 食指, 中指, 无名指, 小指]
            1 = 该手指伸出
            0 = 该手指弯曲
        例如：[0, 1, 1, 0, 0] = 食指和中指伸出（V 手势）
    """
    # 初始化五指状态，默认全部弯曲
    fingers = [0, 0, 0, 0, 0]

    # 安全检查：如果关键点数量不对，直接返回全弯曲状态
    if not hand or len(hand) != 21:
        return fingers

    # -----------------------------------------------------------------------
    # 拇指判断（用 x 坐标比较，因为拇指主要横向运动）
    #
    # 关键点说明：
    #   hand[4] = 拇指指尖（最顶端的点，编号 4）
    #   hand[2] = 拇指第二关节 CMC（掌根附近的关节，编号 2）
    #
    # 镜像画面下的逻辑：
    #   MediaPipe "Left" 标签 → 屏幕右侧的手 → 用户右手
    #     用户右手伸出拇指时，拇指向右 → 指尖 x > 关节 x → hand[4][1] > hand[2][1]
    #   MediaPipe "Right" 标签 → 屏幕左侧的手 → 用户左手
    #     用户左手伸出拇指时，拇指向左 → 指尖 x < 关节 x → hand[4][1] < hand[2][1]
    # -----------------------------------------------------------------------
    if handedness == "Left":
        # 用户右手：指尖在关节右边 = 伸出
        fingers[0] = 1 if hand[4][1] > hand[2][1] else 0
    elif handedness == "Right":
        # 用户左手：指尖在关节左边 = 伸出
        fingers[0] = 1 if hand[4][1] < hand[2][1] else 0
    else:
        # 无法确定左右手时：看拇指是否明显横向伸出
        # 如果水平位移（x方向）大于垂直位移（y方向），认为拇指是横向展开的 = 伸出
        fingers[0] = 1 if abs(hand[4][1] - hand[2][1]) > abs(hand[4][2] - hand[2][2]) else 0

    # -----------------------------------------------------------------------
    # 四根手指判断（用 y 坐标比较）
    #
    # 屏幕坐标 y 轴向下！y 值小 = 位置在上方
    # 手指伸直时，指尖在关节上方，即指尖 y < 关节 y
    #
    # 各手指的关键点：
    #   食指：指尖 = hand[8]，PIP关节 = hand[6]
    #   中指：指尖 = hand[12]，PIP关节 = hand[10]
    #   无名指：指尖 = hand[16]，PIP关节 = hand[14]
    #   小指：指尖 = hand[20]，PIP关节 = hand[18]
    #
    # 格式：hand[n][2] 取的是第 2 个元素（y 坐标），[0]=编号, [1]=x, [2]=y
    # -----------------------------------------------------------------------

    # 食指：指尖(8)比PIP关节(6)更靠上（y值更小）= 伸出
    if hand[8][2] < hand[6][2]:
        fingers[1] = 1

    # 中指：指尖(12)比PIP关节(10)更靠上 = 伸出
    if hand[12][2] < hand[10][2]:
        fingers[2] = 1

    # 无名指：指尖(16)比PIP关节(14)更靠上 = 伸出
    if hand[16][2] < hand[14][2]:
        fingers[3] = 1

    # 小指：指尖(20)比PIP关节(18)更靠上 = 伸出
    if hand[20][2] < hand[18][2]:
        fingers[4] = 1

    return fingers
