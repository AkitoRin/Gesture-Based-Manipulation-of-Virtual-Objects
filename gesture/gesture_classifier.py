# =============================================================================
# 文件：gesture/gesture_classifier.py
# 职责：【识别层第二步 - 手势分类】
#       接收五指状态列表，通过规则匹配，输出具体的手势名称字符串
#
# 输入：fingers = [thumb, index, middle, ring, pinky] 
# 输出：手势名称字符串，例如 "FIST", "OPEN_HAND", "V_SIGN", "UNKNOWN" 等
#
# 当前支持的手势：（默认 1=伸出, 0=弯曲）
#   [0,0,0,0,0] → FIST       握拳
#   [1,1,1,1,1] → OPEN_HAND  张开手掌
#   [0,1,0,0,0] → INDEX_UP   食指朝上
#   [0,1,1,0,0] → V_SIGN     剪刀手/胜利手势
#   [1,0,0,0,0] → THUMBS_UP / THUMBS_DOWN  竖拇指（上/下取决于拇指方向）
#   [1,1,0,0,1] → ROCK       摇滚手势
#   [1,0,0,0,1] → CALL       打电话手势
#   [0,1,1,1,0] → THREE      三根手指（中间三根）
#   [0,1,1,1,1] → FOUR       四根手指（四根伸出）
#   [1,1,1,1,0] → FOUR_THUMB 拇指+三指（不含小指）
#   [0,0,0,0,1] → PINKY_UP   只有小指伸出
#   其他         → UNKNOWN    未知手势
# =============================================================================


def classify_gesture(fingers, hand=None):
    """
    @function:
        根据五指状态列表匹配并返回手势名称

    @params:
        fingers (list): 五指状态，格式为 [thumb, index, middle, ring, pinky]
            由 gesture/finger_state.py 中的 get_finger_state() 生成

        hand (list, 可选): 原始关键点数据（21 个点的列表），格式同 find_positions() 的输出
            仅在需要判断拇指朝向时使用（THUMBS_UP vs THUMBS_DOWN）
            其他情况下可以不传，默认为 None

    @returns:
        str: 手势名称字符串，全大写，用下划线分隔，例如 "FIST"、"V_SIGN"、"UNKNOWN"
    """
    # 把列表里的五个值解包成独立变量，方便后面写条件判断
    # t=拇指, i=食指, m=中指, r=无名指, p=小指
    t, i, m, r, p = fingers

    # -----------------------------------------------------------------------
    # 基础手势匹配（直接比较整个列表是否相等）
    # -----------------------------------------------------------------------

    # 全部弯曲 → 握拳
    if fingers == [0, 0, 0, 0, 0]:
        return "FIST"

    # 全部伸出 → 张开手掌
    if fingers == [1, 1, 1, 1, 1]:
        return "OPEN_HAND"

    # 只有食指伸出 → 食指指向上方
    if fingers == [0, 1, 0, 0, 0]:
        return "INDEX_UP"

    # 食指 + 中指伸出 → 剪刀手（胜利手势）
    if fingers == [0, 1, 1, 0, 0]:
        return "V_SIGN"

    # -----------------------------------------------------------------------
    # 拇指系手势（需要额外判断拇指朝向）
    # -----------------------------------------------------------------------

    # 只有拇指伸出 → 区分"竖大拇指向上"和"竖大拇指向下"
    if fingers == [1, 0, 0, 0, 0]:
        if hand is not None:
            # hand[4][2] = 拇指指尖的 y 坐标
            # hand[0][2] = 手腕的 y 坐标
            # 屏幕 y 轴向下，y 值越小越靠上
            # 拇指指尖 y < 手腕 y → 拇指在手腕上方 → 竖大拇指向上
            return "THUMBS_UP" if hand[4][2] < hand[0][2] else "THUMBS_DOWN"
        # 如果没有提供关键点数据，默认认为是向上
        return "THUMBS_UP"

    # -----------------------------------------------------------------------
    # 组合手势匹配
    # -----------------------------------------------------------------------

    # 拇指 + 食指 + 小指伸出，中指和无名指弯曲 → 摇滚手势 \m/
    if fingers == [1, 1, 0, 0, 1]:
        return "ROCK"

    # 拇指 + 小指伸出，其余弯曲 → 打电话手势（模拟话筒）
    if fingers == [1, 0, 0, 0, 1]:
        return "CALL"

    # 食指 + 中指 + 无名指伸出（三根中间手指） → 数字 3
    if fingers == [0, 1, 1, 1, 0]:
        return "THREE"

    # 食指 + 中指 + 无名指 + 小指伸出（四根手指，拇指收起） → 数字 4
    if fingers == [0, 1, 1, 1, 1]:
        return "FOUR"

    # 拇指 + 食指 + 中指 + 无名指伸出（四根，小指收起） → 带拇指的四
    if fingers == [1, 1, 1, 1, 0]:
        return "FOUR_THUMB"

    # 只有小指伸出 → 小指朝上
    if fingers == [0, 0, 0, 0, 1]:
        return "PINKY_UP"

    # 以上都不匹配 → 未知手势
    return "UNKNOWN"
